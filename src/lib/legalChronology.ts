export function compareLawChronology(a:{slug:string;title:string},b:{slug:string;title:string}) {
 return (LAW_CHRONOLOGY[b.slug]?.date ?? '').localeCompare(LAW_CHRONOLOGY[a.slug]?.date ?? '') || a.title.localeCompare(b.title,'pt-BR') || a.slug.localeCompare(b.slug);
}
export function lawChronologyLabel(slug:string) {
 const row=LAW_CHRONOLOGY[slug];
 if(!row)return 'Data legislativa não identificada';
 const date=row.date.split('-').reverse().join('/');
 return `${row.kind==='amendment'?'Alteração legislativa':'Diploma original'}: ${date}${row.state==='future'?' · vigência futura':''}`;
}
export function compareMaterialRevision(a:{title:string;updated_at?:string},b:{title:string;updated_at?:string}) {
 const time=(value?:string)=>{const parsed=Date.parse(value ?? '');return Number.isFinite(parsed)?parsed:0;};
 return time(b.updated_at)-time(a.updated_at) || a.title.localeCompare(b.title,'pt-BR');
}
