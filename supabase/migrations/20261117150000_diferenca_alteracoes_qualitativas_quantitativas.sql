## Alterações qualitativas e quantitativas — como diferenciar

Em Contabilidade, os termos **qualitativa** e **quantitativa** podem ser usados para classificar mudanças no patrimônio. Eles também podem aparecer em outro contexto, relacionado à qualidade da informação contábil.

### Alteração quantitativa do patrimônio

A alteração quantitativa modifica o valor do patrimônio líquido. Ela ocorre quando há receita, despesa, lucro ou prejuízo.

**Exemplo:** a empresa presta um serviço e recebe R$ 5.000. O Caixa aumenta e a receita também aumenta. Como a riqueza da entidade aumentou, houve alteração quantitativa.

Outro exemplo: uma despesa de aluguel de R$ 2.000 reduz o resultado e, em regra, o Patrimônio Líquido. Também é alteração quantitativa.

### Alteração qualitativa do patrimônio

A alteração qualitativa muda a composição do patrimônio, mas não muda seu valor total.

**Exemplo:** a empresa compra um computador de R$ 4.000 à vista. A conta Computadores aumenta R$ 4.000 e a conta Caixa diminui R$ 4.000. A empresa apenas trocou um bem por outro. O valor total do patrimônio permanece igual.

### Fato misto

O fato misto reúne uma alteração qualitativa e uma quantitativa.

**Exemplo:** pagamento de uma dívida de R$ 10.000 com juros de R$ 1.000. A dívida diminui e o Caixa sai, o que é a parte qualitativa. Os juros são uma despesa que reduz o Patrimônio Líquido, o que é a parte quantitativa.

### Quadro de diferenciação

| Operação | Classificação | Motivo |
|---|---|---|
| Compra de computador à vista | Qualitativa | Troca Caixa por Computador |
| Compra de mercadoria a prazo | Qualitativa | Aumenta Estoque e Fornecedores |
| Recebimento de receita | Quantitativa | Aumenta o Patrimônio Líquido |
| Reconhecimento de despesa | Quantitativa | Reduz o Patrimônio Líquido |
| Pagamento de dívida sem juros | Qualitativa | Reduz Caixa e a obrigação |
| Pagamento de dívida com juros | Mista | Troca patrimonial e redução do PL pelos juros |

### Não confunda os dois usos de “qualitativa”

Nas questões sobre **alterações patrimoniais**, qualitativa significa mudança na composição do patrimônio.

Nas questões sobre **características qualitativas da informação contábil**, o assunto é a qualidade da informação apresentada. Nessa segunda utilização aparecem neutralidade, tempestividade, continuidade, materialidade e compreensibilidade.

**Resumo para a prova:**

- Alteração qualitativa: muda a composição do patrimônio.
- Alteração quantitativa: muda o valor do Patrimônio Líquido.
- Alteração mista: faz as duas coisas.
- Característica qualitativa da informação: avalia como a informação contábil é apresentada.

