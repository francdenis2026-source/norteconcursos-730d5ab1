## 1. Estrutura do Patrimônio Líquido

O resumo enviado apresenta, após as alterações legislativas nele descritas, as seguintes contas e elementos no PL:
- Capital social;
- (-) Capital a realizar;
- Reservas de lucros;
- Reservas de capital;
- Ajuste de avaliação patrimonial;
- (-) Prejuízos acumulados;
- (-) Ações em tesouraria.

O capital social é composto pelas ações subscritas na constituição da sociedade ou no aumento de capital. O material também explica que gastos com emissão de ações reduzem o valor obtido do capital social.

## 2. Reservas de capital

O resumo apresenta como reservas de capital:
- ágio na emissão de ações;
- produto da alienação de partes beneficiárias;
- produto da alienação de bônus de subscrição.

O material afirma que esses valores não se configuram como receita e são contabilizados diretamente no PL. Também lista utilizações possíveis, como absorção de prejuízos não suportados por reservas de lucros e lucros acumulados, resgate/reembolso/compra de ações, incorporação ao capital e pagamento de dividendos a ações preferenciais quando assegurado.

## 3. Reservas de lucros

O resumo lista:
- reserva legal;
- reservas estatutárias;
- reservas para contingências;
- reservas de incentivos fiscais;
- reservas de retenção de lucros;
- reserva de lucros a realizar;
- reserva especial para dividendos obrigatórios não distribuídos;
- reserva de prêmio na emissão de debêntures.

## 4. Reserva legal

Segundo o resumo, a reserva legal corresponde a 5% do lucro líquido do exercício antes de qualquer destinação, respeitado o limite obrigatório de 20% do capital social realizado.

O material também apresenta limite facultativo em que reserva legal somada às reservas de capital não ultrapasse 30% do capital social.

A reserva legal tem por finalidade assegurar a integridade do capital social e pode ser utilizada para aumentar o capital ou compensar prejuízos, conforme o quadro do material.

## 5. Exemplo resolvido — questão Consulplan/CFC 2020.2

Dados:
- capital social integralizado: R$ 70.400;
- reserva legal já existente: R$ 6.400;
- lucro líquido do exercício: R$ 57.600.

Cálculo da parcela de 5%:
57.600 × 5% = **R$ 2.880**.

Limite obrigatório de 20% do capital social:
70.400 × 20% = R$ 14.080.

Reserva existente mais a parcela calculada:
6.400 + 2.880 = R$ 9.280.

Como R$ 9.280 não ultrapassa o limite de R$ 14.080, a constituição integral de R$ 2.880 cabe no limite. A alternativa correspondente no exercício é **A — R$ 2.880,00**.

## 6. Reserva para contingências e reserva de lucros a realizar

O resumo diferencia reserva para contingências e provisão para contingências:
- reserva para contingências: destinação de parcela do lucro no PL para compensar diminuição futura do lucro;
- provisão para contingências: passivo relativo a fato gerador já ocorrido, com contrapartida em despesa.

A reserva de lucros a realizar é apresentada para a situação em que o dividendo obrigatório calculado supera a parcela realizada do lucro líquido, permitindo destinar o excesso à reserva, conforme a descrição do material.

## 7. Dividendos

O resumo apresenta regras de destinação de lucros e dividendos obrigatórios. Se o estatuto for omisso, o quadro apresenta como base 50% do lucro líquido ajustado, com os ajustes indicados no próprio resumo. O material também diferencia dividendos adicionais declarados após o período contábil daqueles declarados antes da aprovação pela assembleia.

## Pegadinhas
- A reserva legal é calculada sobre o lucro líquido antes de qualquer destinação, conforme o resumo.
- Verifique o limite de 20% do capital social realizado.
- Reserva de capital não é receita do exercício no tratamento apresentado.
- Reserva para contingências fica no PL; provisão para contingências fica no passivo.
- Não confunda lucro líquido com parcela realizada do lucro.

