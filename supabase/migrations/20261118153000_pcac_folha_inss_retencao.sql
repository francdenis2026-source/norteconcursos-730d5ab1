## INSS retido versus patronal — exemplo didático

Salário bruto de R$ 3.000, INSS retido hipotético de R$ 300 e patronal de R$ 600. Sem outras rubricas, salários a pagar = R$ 2.700; INSS a recolher = R$ 900; passivo total = R$ 3.600. Despesa/custo de salários = R$ 3.000 e encargo patronal = R$ 600. A retenção já integra o bruto e não constitui custo adicional. Macete: retido desconta do líquido; patronal acrescenta ao custo. Valores hipotéticos, não alíquotas legais. Fundamento: regime de competência, CPC 33 e Lei 8.212/1991, arts. 22 e 30, conforme regime aplicável.

### Questões autorais — estilo IDECAN

**1.** Uma sociedade apurou salários brutos de R$ 10.000, INSS retido de R$ 800 e contribuição patronal de R$ 2.000. Desconsiderando outras rubricas e pagamentos, o passivo total da folha é:
- A) R$ 9.200
- B) R$ 10.000
- C) R$ 10.800
- D) R$ 12.000
- E) R$ 12.800

Gabarito D. A é somente o salário líquido; B ignora o patronal; C duplica retenção e ignora patronal; D soma bruto e patronal; E duplica retenção.

**2.** A retenção previdenciária incidente sobre o salário do empregado representa, para a empregadora:
- A) Receita financeira.
- B) Despesa patronal adicional.
- C) Obrigação de recolhimento que reduz o salário líquido a pagar.
- D) Redução da despesa de salários brutos.
- E) Ativo a recuperar.

Gabarito C. A não é receita; B confunde retenção e contribuição própria; C descreve a obrigação; D não reduz a despesa bruta; E não constitui direito a recuperar.
