## Vocabulário das operações cobradas em questões

Esta seção traduz os termos técnicos dos enunciados para situações do cotidiano e mostra quais contas costumam ser afetadas. A classificação indicada considera as condições simplificadas descritas em cada exemplo; juros, descontos, encargos ou outros efeitos podem mudar a análise.

### 1. Compra de mercadorias parcialmente à vista e parcialmente a prazo

- **Mercadorias/estoque:** bens comprados para revenda.
- **À vista:** a parte paga imediatamente, normalmente por caixa ou banco.
- **A prazo:** a parte que ficará para pagamento futuro, gerando uma obrigação com o fornecedor.
- **O que acontece:** o estoque aumenta; o caixa/banco diminui pela parte paga; fornecedores aumenta pela parte ainda não paga.
- **Exemplo:** compra de R$ 1.000 em mercadorias, pagando R$ 400 agora e deixando R$ 600 para depois. A empresa registra estoque de R$ 1.000, saída de banco de R$ 400 e dívida com fornecedor de R$ 600.
- **Como pensar:** sem juros ou outros efeitos, houve troca e reorganização de contas patrimoniais, sem alteração imediata do patrimônio líquido.

### 2. Recebimento de duplicatas pelo valor nominal

- **Duplicata:** título/documento que representa um direito de receber de um cliente por uma venda ou serviço a prazo.
- **Recebimento:** o cliente paga e a empresa recebe o dinheiro no caixa ou banco.
- **Valor nominal:** valor escrito no título, sem acréscimo de juros nem desconto na hipótese apresentada.
- **O que acontece:** aumenta caixa/bancos e diminui duplicatas a receber pelo mesmo valor.
- **Exemplo:** a empresa tinha uma duplicata de R$ 700 e recebeu exatamente R$ 700. Sai o direito de receber; entra dinheiro.
- **Como pensar:** se o recebimento ocorre pelo valor nominal, sem juros, desconto ou perda, há apenas troca entre contas do ativo.

### 3. Contratação de financiamento para comprar veículo

- **Financiamento:** dinheiro obtido de uma instituição financeira, que deverá ser devolvido conforme contrato, geralmente com encargos.
- **Veículo:** bem que, quando adquirido para uso da entidade, integra o ativo imobilizado.
- **O que acontece na operação completa:** o veículo entra no ativo e nasce uma obrigação de pagar o financiamento no passivo. Se o banco paga diretamente ao vendedor, o registro considera a entrada do veículo e a dívida correspondente.
- **Exemplo:** veículo de R$ 60.000 financiado integralmente. A entidade reconhece o veículo no ativo imobilizado e o financiamento a pagar no passivo, observadas as regras de mensuração e os encargos.
- **Atenção:** a mera assinatura de uma proposta ou contrato ainda não executado não deve ser confundida automaticamente com o reconhecimento do veículo e da dívida. Observe se o financiamento foi efetivado e se o bem foi adquirido/entregue.
- **Como pensar:** na operação de aquisição financiada, aumentam um bem e uma obrigação; por si só, isso não representa receita nem despesa.

### 4. Depreciação de imóvel fabril

- **Imóvel fabril:** prédio utilizado na atividade industrial da empresa.
- **Depreciação:** reconhecimento contábil da perda de potencial de serviço do ativo ao longo de sua vida útil, em razão do uso, passagem do tempo e outros fatores pertinentes.
- **Despesa de depreciação:** parcela reconhecida no resultado do período quando o imóvel é utilizado na administração ou produção, conforme a finalidade. Na produção, pode integrar o custo de fabricação e ser apropriada ao resultado conforme o estoque é vendido/consumido.
- **Depreciação acumulada:** conta redutora do imobilizado, que reúne a depreciação reconhecida ao longo do tempo.
- **Exemplo:** prédio fabril depreciável de R$ 1.000.000, com quota anual simplificada de R$ 20.000. O registro reconhece a depreciação do período e reduz o valor contábil líquido do imóvel por meio da depreciação acumulada.
- **Atenção:** terreno normalmente não é depreciado; prédio e terreno devem ser considerados separadamente quando aplicável. A depreciação não significa que a empresa pagou dinheiro naquele momento.
- **Como pensar:** há reconhecimento de consumo econômico do ativo e efeito de despesa/custo; não é simples troca entre duas contas patrimoniais.

### 5. Amortização de empréstimo com juros de mora

- **Amortização do empréstimo:** pagamento que reduz o principal da dívida. Neste contexto, “amortização” não significa amortização de ativo intangível.
- **Principal:** valor originalmente tomado emprestado, ainda não devolvido.
- **Juros de mora:** encargo cobrado pelo atraso no pagamento.
- **O que acontece:** a saída de dinheiro reduz o caixa/banco; a parcela do principal reduz a obrigação do empréstimo; os juros de mora são despesa financeira e reduzem o resultado/patrimônio líquido.
- **Exemplo:** a empresa paga R$ 1.100: R$ 1.000 correspondem ao principal da dívida e R$ 100 aos juros pelo atraso. A dívida diminui R$ 1.000, o banco diminui R$ 1.100 e a despesa financeira de R$ 100 reduz o resultado.
- **Como pensar:** há uma parte de troca patrimonial (baixa da dívida e saída de dinheiro) e uma parte que reduz o patrimônio líquido (juros). Por isso, na hipótese descrita, a operação reúne efeitos permutativos e modificativos.

