| Parcialmente à vista | Uma parte é paga agora | Caixa/Bancos |
| Parcialmente a prazo | Uma parte será paga depois | Fornecedores |
| Mercadorias | Produtos comprados para revenda | Estoques |
| Duplicatas | Direito de receber de clientes | Duplicatas a receber |
| Valor nominal | Valor original escrito no título | Caixa/Bancos e Duplicatas a receber |
| Financiamento | Dinheiro emprestado para adquirir um bem | Imobilizado e Financiamentos a pagar |
| Imóvel fabril | Prédio usado na fábrica | Imobilizado |
| Depreciação | Reconhecimento do consumo econômico do bem | Despesa/Custo e Depreciação acumulada |
| Amortização do empréstimo | Devolução do principal da dívida | Empréstimos a pagar e Caixa/Bancos |
| Juros de mora | Encargo pelo atraso | Despesa financeira |

### Roteiro para resolver enunciados desse tipo

1. Circule os verbos: comprar, receber, contratar, depreciar, amortizar e pagar.
2. Identifique o que entra e o que sai.
3. Separe o principal da dívida dos juros e demais encargos.
4. Pergunte se houve apenas troca entre contas patrimoniais ou se apareceu receita/despesa.
5. Verifique se o patrimônio líquido foi afetado.
6. Se houver troca patrimonial e também alteração do patrimônio líquido no mesmo fato, analise a hipótese de fato misto.

