## 1. O que é tomar decisão?
É escolher uma alternativa entre opções para resolver problema ou aproveitar oportunidade. Uma decisão administrativa precisa considerar objetivo, informação disponível, regras, recursos, riscos e consequências.

O processo começa quando existe diferença entre situação atual e desejada, ou quando surge oportunidade que exige escolha.

## 2. Etapas do processo decisório
1. Identificar e definir o problema sem confundir sintoma e causa.
2. Reunir informações relevantes e verificar sua confiabilidade.
3. Estabelecer critérios de decisão.
4. Construir alternativas viáveis.
5. Comparar custos, benefícios, riscos e impactos.
6. Escolher e justificar a alternativa.
7. Implementar, comunicar e atribuir responsabilidades.
8. Acompanhar resultados e rever a decisão quando necessário.

Exemplo: atrasos no atendimento podem decorrer de formulário incompleto, sistema lento ou falta de pessoal. Comprar computadores sem diagnosticar a causa pode não resolver o problema.

## 3. Decisões programadas e não programadas
- Programadas: repetitivas e rotineiras, podem seguir regras, procedimentos e padrões.
- Não programadas: novas, complexas ou pouco estruturadas, exigem análise e julgamento.

Uma situação pode começar como não programada e, após aprendizado, gerar procedimento padronizado para casos futuros.

## 4. Racionalidade limitada
O gestor nem sempre dispõe de todas as informações, tempo ou capacidade para avaliar todas as alternativas. A racionalidade é limitada por incerteza, prazos, recursos e complexidade. Por isso, a decisão pode buscar solução satisfatória e viável, não necessariamente uma solução matematicamente perfeita.

Isso não autoriza arbitrariedade: critérios, justificativas, legalidade e transparência continuam necessários.

## 5. Critérios e vieses
Critérios podem incluir legalidade, custo, prazo, qualidade, risco, impacto social e viabilidade. Vieses como confirmação (buscar apenas dados que apoiam opinião prévia), ancoragem (dar peso excessivo à primeira informação) e excesso de confiança podem distorcer escolhas.

Reduza vieses consultando fontes independentes, explicitando critérios e registrando alternativas rejeitadas.

## 6. Controle administrativo
Controle verifica se a execução está de acordo com objetivos, padrões e regras. Compara o realizado com o planejado, identifica desvios, investiga causas e orienta correções.

Tipos conforme o momento:
- **Prévio ou preventivo:** antes da execução, para evitar falha.
- **Concomitante:** durante a execução, para acompanhar e corrigir em tempo.
- **Posterior:** depois da atividade, para avaliar resultados e responsabilização quando cabível.

## 7. Controle não é apenas punição
Controle também previne desperdício, melhora processos, protege recursos, aumenta confiabilidade e permite aprendizagem. A correção deve atacar causa do desvio, e não apenas o sintoma.

## 8. Exemplo aplicado
Uma unidade define meta de concluir 90% dos requerimentos no prazo. Antes de iniciar, cria checklist (preventivo); durante o mês, acompanha fila e corrige gargalo (concomitante); no fechamento, calcula percentual e analisa atrasos (posterior).

