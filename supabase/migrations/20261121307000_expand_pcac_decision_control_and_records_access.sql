Um relatório de atendimento contém estatísticas gerais e nomes, telefones e dados pessoais de usuários. A unidade avalia a base legal e a finalidade do acesso, protege informações pessoais quando necessário e fornece versão com dados agregados ou trechos ocultados, mantendo o original íntegro e registrando a operação.

