## 1. Regra geral e exceções
A Administração Pública deve observar transparência e direito de acesso à informação, respeitando hipóteses legais de restrição, proteção de dados pessoais e sigilos previstos em lei.

Não se deve presumir que todo documento público é irrestrito nem que qualquer presença de dado pessoal justifica negar o processo inteiro.

## 2. Informação pessoal e informação sigilosa
Informação pessoal diz respeito a pessoa natural identificada ou identificável. Pode exigir proteção para resguardar intimidade, vida privada, honra e imagem, conforme regras legais.

Informação classificada como sigilosa é submetida a restrição formal nos termos da legislação de acesso à informação, com fundamento e prazo aplicáveis. Dado pessoal e informação classificada como sigilosa não são categorias idênticas.

## 3. Acesso parcial e ocultação
Quando um documento mistura conteúdo público e informação protegida, deve-se avaliar se é possível fornecer acesso parcial, tarjando ou ocultando apenas o trecho restrito, sem comprometer o sentido do restante.

A decisão deve indicar fundamento e observar procedimento institucional. Não se deve remover páginas ou ocultar informação sem registro.

## 4. Proteção de dados no arquivo
Boas práticas incluem:
- coletar e manter apenas dados necessários à finalidade;
- limitar acesso conforme atribuição;
- proteger cópias físicas e digitais;
- registrar consultas e movimentações relevantes;
- evitar envio por canais não autorizados;
- definir retenção e destinação conforme regras;
- preservar integridade e contexto documental.

Proteção não significa impedir todo uso legítimo: significa controlar finalidade, necessidade e acesso.

## 5. Controle de acesso
O acesso deve seguir perfil e necessidade funcional. Autenticação confirma identidade; autorização define o que a pessoa pode consultar ou alterar. Registro de auditoria permite identificar acessos e operações.

Não compartilhe credenciais. Acesso técnico ao sistema não equivale a autorização legal para consultar qualquer conteúdo.

## 6. Classificação de documentos e sigilo
A classificação arquivística organiza documentos por função e atividade; a classificação de sigilo estabelece restrição de acesso nos termos legais. São procedimentos diferentes, apesar do uso da palavra “classificação”.

Na prova, observe o contexto: plano de classificação e temporalidade remetem à organização arquivística; grau de sigilo e prazo de restrição remetem à legislação de acesso à informação.

