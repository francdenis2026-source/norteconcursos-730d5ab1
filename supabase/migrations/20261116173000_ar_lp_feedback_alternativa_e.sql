### Se você marcou a alternativa E

O erro mais provável foi somar também os **R$ 600.000** do empréstimo à sociedade em que havia apenas participação minoritária, sem influência significativa.

A questão apresenta quatro valores, mas nem todos entram no ARLP:

- R$ 500.000 entram porque o empréstimo foi concedido a uma **coligada**.
- R$ 700.000 entram porque foi concedido a uma **controlada**.
- R$ 600.000 não entra pela regra especial, pois participação minoritária sem influência significativa não torna a sociedade coligada ou controlada.
- R$ 800.000 entram porque o vencimento ocorre depois do término do exercício seguinte.

Assim, não se deve fazer **R$ 500.000 + R$ 700.000 + R$ 600.000 + R$ 800.000**. Esse cálculo inclui um valor que não atende aos critérios apresentados.

O cálculo correto é:

**R$ 500.000 + R$ 700.000 + R$ 800.000 = R$ 2.000.000.**

A alternativa E representa a consequência de não separar cada operação e de considerar que toda participação acionária gera automaticamente uma relação de coligação. Para evitar esse erro, procure primeiro as expressões **“coligada”**, **“controlada”**, **“influência significativa”**, **“participação minoritária”** e **“após o exercício seguinte”**.

