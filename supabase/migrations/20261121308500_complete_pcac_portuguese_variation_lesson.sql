> **QUESTÃO DE ABERTURA — padrão IDECAN (autoral)**
>
> Em um relatório oficial destinado à autoridade policial, a escolha linguística mais adequada é:
>
> A) usar gírias para aproximar o leitor. B) empregar linguagem clara, objetiva e compatível com a norma-padrão e o contexto institucional. C) reproduzir abreviações de mensagens informais sem explicação. D) usar expressões ambíguas para resumir. E) evitar pontuação.
>
> **Resolução:** o gênero, o destinatário e a finalidade exigem clareza, precisão e registro formal. Gabarito: **B**.

## 1. Língua como fenômeno social
A língua é viva e varia conforme região, grupo social, época, situação comunicativa e modalidade. A variação não significa, por si só, erro ou incapacidade. Os falantes ajustam suas escolhas às comunidades e aos contextos em que interagem.

## 2. Tipos de variação
- **Diatópica/geográfica:** diferenças regionais de pronúncia, vocabulário e construções.
- **Diastrática/social:** diferenças associadas a grupos, profissão, escolaridade, idade e redes sociais.
- **Diacrônica/histórica:** mudanças ao longo do tempo.
- **Diafásica/situacional:** escolha do registro conforme interlocutor, finalidade e formalidade.
- **Diamésica/modalidade:** diferenças entre fala, escrita e meios de comunicação.

## 3. Norma-padrão e norma culta
A norma-padrão é uma referência convencional para usos formais e institucionais. A norma culta está relacionada a usos de falantes escolarizados em situações monitoradas. Os termos não devem ser tratados como sinônimos absolutos em toda abordagem.

A prova pode exigir a norma-padrão em redação oficial, mas a análise linguística deve reconhecer a diversidade real.

## 4. Adequação linguística
A adequação considera quem fala e para quem, qual é o objetivo, qual gênero está sendo produzido, qual canal será utilizado e qual grau de formalidade é esperado.

Uma gíria pode ser adequada entre amigos e inadequada em um relatório. Isso não significa que a gíria seja defeito em qualquer situação; significa que o registro deve corresponder ao contexto.

## 5. Oralidade e escrita
A fala costuma contar com entonação, gestos, pausas e interação imediata. A escrita exige maior explicitação de referências e organização, embora mensagens digitais aproximem recursos de fala e escrita.

A diferença não é absoluta: há fala formal e escrita informal. Uma entrevista oficial pode ser oral e formal; uma mensagem privada pode ser escrita e informal.

## 6. Preconceito linguístico
Ocorre quando uma variedade ou seus falantes são desqualificados por origem, região, classe ou grupo. A avaliação escolar da adequação à norma-padrão não autoriza discriminar pessoas por sua forma de falar.

## 7. Exemplo aplicado
Uma equipe conversa informalmente no intervalo e depois elabora relatório sobre a mesma ocorrência. A conversa pode conter marcas de oralidade; o relatório deve organizar os fatos, identificar fontes, usar linguagem objetiva e evitar expressões vagas. O conteúdo factual não deve mudar, mas o registro se adapta ao gênero.

## 8. Como cai em prova
- identificar regionalismos e gírias;
- reconhecer formalidade e informalidade;
- classificar tipos de variação;
- distinguir fala e escrita;
- avaliar adequação ao gênero e interlocutor;
- reconhecer preconceito linguístico.

## 9. Treino de classificação
1. “A palavra usada é comum no Norte do país, mas pouco conhecida em outras regiões.” → variação diatópica.
2. “Uma expressão antiga deixa de ser usada pelas gerações mais novas.” → variação diacrônica.
3. “O mesmo servidor conversa informalmente com colegas e usa linguagem formal em ofício.” → variação diafásica.
4. “Uma comunidade profissional utiliza termos técnicos próprios.” → pode envolver variação diastrática, ligada ao grupo/profissão.
5. “Uma mensagem usa emojis e abreviações próprias do aplicativo.” → marcas da modalidade/meio, associadas à variação diamésica.

