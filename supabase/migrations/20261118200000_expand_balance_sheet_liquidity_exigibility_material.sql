### 1. Primeiro, entenda o que o balanço está mostrando

Imagine uma pessoa que tem dinheiro na carteira, dinheiro no banco, um carro, uma casa financiada e contas a pagar. O Balanço Patrimonial organiza esses elementos em uma data.

- **Ativo:** recursos e direitos controlados pela entidade. Em linguagem simples: o que a empresa tem ou tem a receber.
- **Passivo exigível:** obrigações com terceiros. É o que a empresa deve.
- **Patrimônio Líquido (PL):** interesse residual dos proprietários depois de deduzir os passivos do ativo.

Equação fundamental: **Ativo = Passivo exigível + Patrimônio Líquido**.

### 2. Grau de liquidez — como o Ativo é organizado

**Liquidez** é a facilidade ou rapidez com que um bem ou direito pode ser convertido em dinheiro, sem perda relevante de valor.

A Lei nº 6.404/1976, art. 178, § 1º, determina que as contas do Ativo sejam apresentadas em **ordem decrescente de liquidez**: começa pelo que vira dinheiro mais facilmente e avança para o que demora mais.

Exemplo de uma empresa:
1. Caixa: o dinheiro já está disponível.
2. Banco conta movimento: dinheiro disponível na conta.
3. Clientes a receber: a empresa ainda precisa receber.
4. Estoques: precisam ser vendidos para virar dinheiro.
5. Máquinas e prédio usados na operação: normalmente não são mantidos para venda e são convertidos em dinheiro com muito menos rapidez.

**Macete:** liquidez lembra “liquidar”, transformar em dinheiro. No Ativo, o mais líquido vem primeiro.

### 3. Grau de exigibilidade — como entender o Passivo

**Exigibilidade** é o grau de proximidade ou força com que uma obrigação pode ser cobrada, considerando seu vencimento e os direitos contratuais existentes.

Na apresentação usual do balanço, primeiro aparecem as obrigações de curto prazo (**Passivo Circulante**) e depois as de longo prazo (**Passivo Não Circulante**). Em termos práticos, as obrigações que exigem liquidação mais próxima ficam no grupo circulante.

Exemplo:
- Conta de energia que vence no próximo mês: obrigação circulante.
- Financiamento com parcelas que vencem nos próximos anos: parcelas de curto prazo no circulante e parcelas posteriores no não circulante, conforme os critérios aplicáveis.

**Atenção à pegadinha:** não confunda “ordem decrescente de liquidez” do Ativo com o tratamento das obrigações. Liquidez é facilidade de virar dinheiro; exigibilidade é a possibilidade/prazo de cobrança.

### 4. Ativo Circulante e Ativo Não Circulante

O **Ativo Circulante** reúne, em regra, caixa e equivalentes, ativos que serão realizados, vendidos ou consumidos no ciclo operacional normal, os mantidos para negociação ou aqueles cuja realização se espera até doze meses após a data do balanço.

Exemplos cotidianos:
- dinheiro em caixa e banco;
- clientes que pagarão em breve;
- mercadorias que serão vendidas;
- despesas antecipadas que correspondem ao ciclo/ano seguinte.

O **Ativo Não Circulante** abrange:
- **Realizável a Longo Prazo:** direitos cuja realização ocorre depois do período aplicável ao circulante;
- **Investimentos:** participações permanentes e outros direitos que não se destinam à manutenção da atividade operacional;
- **Imobilizado:** bens corpóreos usados na atividade, como máquinas, veículos e prédios;
- **Intangível:** ativos identificáveis sem substância física, como determinados softwares, marcas e patentes, quando atendidos os critérios de reconhecimento.

**Exemplo:** uma fábrica tem R$ 10 mil no banco, R$ 30 mil em estoque, uma máquina usada na produção e um software reconhecido como ativo. Banco e estoque tendem a ser circulantes; máquina é imobilizado; software pode ser intangível.

### 5. Passivo Circulante e Passivo Não Circulante

- **Passivo Circulante:** obrigações que se enquadram nos critérios de liquidação no ciclo operacional normal, mantidas para negociação ou exigíveis/liquidáveis no horizonte de curto prazo previsto na norma.
- **Passivo Não Circulante:** obrigações que não atendem aos critérios de classificação no circulante, observados os direitos da entidade na data do balanço.

Não basta olhar o nome “financiamento”. É necessário examinar vencimentos, ciclo operacional, cláusulas contratuais e se a entidade tinha, na data do balanço, o direito de postergar a liquidação.

**Exemplo:** financiamento de R$ 120 mil em 36 parcelas. As parcelas que vencem no período circulante são apresentadas no Passivo Circulante; o saldo com vencimento posterior fica no Passivo Não Circulante, respeitados os critérios normativos.

### 6. Cláusula de vencimento antecipado e inadimplemento

Uma cláusula contratual pode permitir que o banco exija a dívida antes do prazo se a empresa descumprir determinada condição.

Para classificar a obrigação, não basta dizer que o contrato é “de longo prazo”. É preciso perguntar: **na data do balanço, a empresa tinha o direito de adiar a liquidação por pelo menos doze meses?**

Se uma quebra contratual torna a dívida exigível à vista na data do balanço, em regra a obrigação é circulante, salvo se o credor tiver concedido, até aquela data, prazo de carência que assegure o direito de postergar a liquidação pelo período exigido pela norma. Uma renegociação ou dispensa concedida somente depois da data do balanço não muda automaticamente a classificação naquela data.

### 7. Ativo não circulante mantido para venda

Um equipamento ou imóvel que antes era usado por vários anos pode passar a ser classificado como **mantido para venda** quando os critérios do pronunciamento específico são atendidos.

Em termos simples, não basta a administração dizer “quero vender”. Em regra, o ativo deve estar disponível para venda imediata em suas condições atuais e a venda deve ser altamente provável, com compromisso da administração e ações efetivas para localizar comprador e concluir a operação.

Quando atende aos critérios do CPC 31 / NBC TG 31:
- o ativo é apresentado separadamente no balanço;
- é classificado no Ativo Circulante;
- é mensurado pelo menor entre valor contábil e valor justo menos despesas de venda, conforme a norma;
- cessa a depreciação ou amortização enquanto estiver classificado como mantido para venda, nos termos do pronunciamento.

**Exemplo:** uma empresa decide vender uma máquina que deixou de usar, já está em condição de venda imediata, foi colocada à venda por preço razoável e a negociação é altamente provável. Se os critérios forem cumpridos, ela pode ser apresentada separadamente como ativo não circulante mantido para venda, no circulante.

### 8. Ativo diferido — cuidado com a terminologia antiga

O **ativo diferido** é uma classificação histórica, presente em versões antigas da Lei das S.A. para certos gastos pré-operacionais e de reestruturação. A estrutura atual do balanço não apresenta o diferido como grupo autônomo do Ativo Não Circulante.

A Lei nº 11.941/2009 alterou a estrutura da Lei nº 6.404/1976 e retirou o diferido dos grupos atuais. A Lei nº 11.638/2007 já havia alterado a estrutura e estabelecido regras de transição para saldos antigos.

**Como a banca pode cobrar:** se a alternativa tratar o ativo diferido como se fosse um grupo normal e atual do balanço, desconfie. Não confunda essa expressão histórica com ativo fiscal diferido, que é outro assunto e possui norma própria.

### 9. Reavaliação de ativos e Patrimônio Líquido

A antiga **reserva de reavaliação** era usada para registrar determinados aumentos de valor de ativos em um modelo contábil anterior. A Lei nº 11.638/2007 extinguiu a possibilidade de constituir novas reservas de reavaliação nos moldes antigos, e a Lei nº 11.941/2009 consolidou a estrutura atual do Patrimônio Líquido.

Isso não significa que toda mudança de valor de ativo seja proibida. As normas atuais admitem mensurações e ajustes específicos, conforme o tipo de ativo e o pronunciamento aplicável. Em situações previstas, certos efeitos podem ser reconhecidos em **Ajustes de Avaliação Patrimonial (AAP)** no Patrimônio Líquido.

**Pegadinha:** não aceite a ideia de que a empresa pode simplesmente reavaliar livremente qualquer ativo e criar uma antiga “reserva de reavaliação”. É necessário identificar a norma e o modelo de mensuração aplicável.

### 10. Estrutura resumida do Balanço Patrimonial

| Lado do Ativo | Lado do Passivo e PL |
|---|---|
| Ativo Circulante | Passivo Circulante |
| Ativo Não Circulante | Passivo Não Circulante |
| — Realizável a Longo Prazo | Patrimônio Líquido |
| — Investimentos | — Capital Social |
| — Imobilizado | — Reservas e ajustes aplicáveis |
| — Intangível | — Ações em tesouraria e prejuízos acumulados como deduções |

### 11. Vocabulário que aparece em provas

- **Disponibilidades:** dinheiro em caixa e recursos bancários de disponibilidade imediata.
- **Direitos realizáveis:** valores que a entidade tem direito de receber ou converter em dinheiro.
- **Ciclo operacional:** tempo entre adquirir/produzir recursos, vender e receber do cliente.
- **Exercício social:** período contábil definido para apuração e apresentação das demonstrações; normalmente coincide com o ano civil, mas há exceções legais.
- **Vencimento:** data em que a obrigação deve ser paga.
- **Exigível:** aquilo que pode ser cobrado conforme as condições legais e contratuais.
- **Mantido para venda:** ativo cujo valor contábil será recuperado principalmente por venda, e não pelo uso contínuo, desde que os critérios normativos sejam satisfeitos.
- **Valor justo:** preço de saída em transação não forçada entre participantes do mercado na data de mensuração.
- **Despesa de venda:** custo incremental diretamente atribuível à alienação, conforme a definição da norma.
- **Ajuste de Avaliação Patrimonial:** componente do PL que recebe determinados efeitos de avaliação previstos nas normas; não é uma autorização genérica para reavaliar bens.

### 12. Como resolver questões de classificação do balanço

1. Identifique se o item fala de Ativo, Passivo ou Patrimônio Líquido.
2. Se for Ativo, pergunte: quão rápido vira dinheiro? É usado na atividade? É um direito de longo prazo?
3. Se for Passivo, pergunte: quando pode ser cobrado? A empresa tem direito de adiar a liquidação?
4. Se aparecer “mantido para venda”, verifique se os critérios do CPC 31 / NBC TG 31 foram cumpridos.
5. Se aparecer “ativo diferido” ou “reserva de reavaliação”, confira se a questão está usando terminologia histórica.
6. Leia a alternativa inteira: uma frase pode começar correta e terminar com uma ordem ou classificação invertida.

### 13. Atenção à atualização normativa

Esta questão é da prova da Polícia Civil de Pernambuco de 2024. Para compreender o item, a referência histórica principal é a Lei nº 6.404/1976 e a estrutura então aplicável da NBC TG 26 / CPC 26, além do CPC 31 / NBC TG 31 para ativos mantidos para venda.

Em 2026, houve evolução normativa: o CPC publicou o CPC 51, e o CFC comunicou retificações relacionadas à NBC 31 e à NBC TG 51. Para questões de provas futuras, deve-se observar a data de corte do edital e a norma indicada nele; não se deve aplicar automaticamente uma norma nova a uma prova anterior.

